-- QALBU database setup compatible with staff_profiles(user_id, role) already created.
-- Run in Supabase > SQL Editor. Safe to run more than once.
create table if not exists public.staff_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'staff' check (role in ('staff','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null check (category in ('Shawl','Bawal','Sarung')),
  price numeric(10,2) not null check (price >= 0),
  description text not null default '',
  image_url text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.staff_profiles enable row level security;
alter table public.products enable row level security;

drop policy if exists "Staff can read own profile" on public.staff_profiles;
create policy "Staff can read own profile" on public.staff_profiles
for select to authenticated using (user_id = auth.uid());

drop policy if exists "Public reads active products" on public.products;
create policy "Public reads active products" on public.products
for select to anon, authenticated using (active = true);

drop policy if exists "Staff reads all products" on public.products;
create policy "Staff reads all products" on public.products for select to authenticated
using (exists(select 1 from public.staff_profiles s where s.user_id=auth.uid() and s.role in ('staff','admin')));

drop policy if exists "Staff inserts products" on public.products;
create policy "Staff inserts products" on public.products for insert to authenticated
with check (exists(select 1 from public.staff_profiles s where s.user_id=auth.uid() and s.role in ('staff','admin')));

drop policy if exists "Staff updates products" on public.products;
create policy "Staff updates products" on public.products for update to authenticated
using (exists(select 1 from public.staff_profiles s where s.user_id=auth.uid() and s.role in ('staff','admin')))
with check (exists(select 1 from public.staff_profiles s where s.user_id=auth.uid() and s.role in ('staff','admin')));

